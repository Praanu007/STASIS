// Builds dashboard/index.html from src/: the React app bundled and inlined with
// its stylesheet into one file with no document skeleton. server.py adds the
// skeleton when it serves the page, and the same file publishes as a preview,
// so the VM needs neither Node nor a network to show the dashboard.
//
//   node build.mjs                    index.html, minified
//   node build.mjs --dev [--out FILE] React's development build, with its warnings
import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const here = (p) => fileURLToPath(new URL(p, import.meta.url));   // the repository path has spaces
const args = process.argv.slice(2);
const dev = args.includes('--dev');
const outFile = args.includes('--out') ? args[args.indexOf('--out') + 1] : here('index.html');
if (!outFile) throw new Error('--out needs a file');

const out = await build({
  entryPoints: [here('src/main.tsx')],
  bundle: true,
  minify: !dev,
  format: 'iife',
  target: 'es2020',
  jsx: 'automatic',
  define: { 'process.env.NODE_ENV': dev ? '"development"' : '"production"' },
  legalComments: 'eof',       // React's MIT notice stays with the code
  write: false,
  logLevel: 'warning',
});
const js = out.outputFiles[0].text.trim();
const css = (await readFile(here('src/styles.css'), 'utf8')).trim();
const head = (await readFile(here('src/head.html'), 'utf8')).trim();

// Inlined, a script ends at the first "</script" whatever the context, and
// "<!--" can change how the rest is parsed; a style ends at "</style".
for (const [what, text, bad] of [['script', js, /<\/script|<!--/i], ['stylesheet', css, /<\/style/i]]) {
  const m = bad.exec(text);
  if (m) throw new Error(`the ${what} contains "${m[0]}" at ${m.index}; it cannot be inlined as is`);
}

const page = `${head}
<!-- Generated by build.mjs from src/ (React + TypeScript): edit the sources, then run "npm run build". -->
<style>
${css}
</style>
<div id="root"></div>
<noscript><p style="padding:24px max(16px, env(safe-area-inset-left, 0px))">The Control Room needs JavaScript.</p></noscript>
<script>
${js}
</script>
`;
await writeFile(outFile, page);
console.log(`${outFile}${dev ? ' (development)' : ''}: ${(page.length / 1024).toFixed(1)} KiB (script ${(js.length / 1024).toFixed(1)} KiB, styles ${(css.length / 1024).toFixed(1)} KiB)`);
